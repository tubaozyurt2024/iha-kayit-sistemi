CREATE TABLE iha (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seri_no                     VARCHAR(50)      NOT NULL,
    model                       VARCHAR(100)     NOT NULL,
    uretici                     VARCHAR(100)     NOT NULL,
    kategori                    VARCHAR(20)      NOT NULL,
    durum                       VARCHAR(20)      NOT NULL,
    maks_irtifa_metre           INTEGER          NOT NULL,
    menzil_km                   DOUBLE PRECISION NOT NULL,
    havada_kalma_suresi_saat    DOUBLE PRECISION NOT NULL,
    azami_kalkis_agirligi_kg    DOUBLE PRECISION NOT NULL,
    uretim_tarihi               DATE             NOT NULL,
    son_bakim_tarihi            DATE,
    created_at                  TIMESTAMP(6)     NOT NULL,
    updated_at                  TIMESTAMP(6)     NOT NULL,

    CONSTRAINT uk_iha_seri_no UNIQUE (seri_no),
    CONSTRAINT ck_iha_kategori CHECK (kategori IN ('MINI', 'TAKTIK', 'MALE', 'HALE')),
    CONSTRAINT ck_iha_durum CHECK (durum IN ('AKTIF', 'BAKIMDA', 'PASIF', 'HURDA')),
    CONSTRAINT ck_iha_pozitif_degerler CHECK (
        maks_irtifa_metre > 0 AND menzil_km > 0
        AND havada_kalma_suresi_saat > 0 AND azami_kalkis_agirligi_kg > 0
    ),
    CONSTRAINT ck_iha_bakim_tarihi CHECK (son_bakim_tarihi IS NULL OR son_bakim_tarihi >= uretim_tarihi)
);

CREATE INDEX ix_iha_durum ON iha (durum);
CREATE INDEX ix_iha_kategori ON iha (kategori);
